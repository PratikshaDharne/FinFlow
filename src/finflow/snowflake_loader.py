"""Snowflake load of the rows changed by a load.  UNTESTED: no Snowflake account available.

Flow (one Snowflake transaction): write_pandas -> STAGING.STG_<ENTITY>, then MERGE into
CURATED.<ENTITY> comparing ROW_HASH. Safe to re-run: the MERGE is idempotent.
The SQL generators below are pure functions and ARE unit-tested.
"""

from __future__ import annotations

import pandas as pd
from sqlalchemy import text

from .config import get_secret
from .errors import CloudIntegrationError, ConfigError
from .logging_utils import get_logger
from .schemas import ENTITIES, Entity
from .utils import retry

log = get_logger("snowflake")

AUDIT_DDL = (
    "ROW_HASH VARCHAR(64) NOT NULL, SOURCE_FILE VARCHAR(255), CREATED_LOAD_ID VARCHAR(40), "
    "UPDATED_LOAD_ID VARCHAR(40), ETL_CREATED_AT TIMESTAMP_NTZ, ETL_UPDATED_AT TIMESTAMP_NTZ"
)


def curated_ddl(spec: Entity) -> str:
    cols = ",\n    ".join(
        f"{c.name.upper()} {c.snowflake_type}{' NOT NULL' if c.required else ''}" for c in spec.columns
    )
    return (
        f"CREATE TABLE IF NOT EXISTS CURATED.{spec.name.upper()} (\n    {cols},\n    {AUDIT_DDL},\n"
        f"    CONSTRAINT PK_{spec.name.upper()} PRIMARY KEY ({spec.pk.upper()})\n);"
    )


def staging_ddl(spec: Entity) -> str:
    cols = ",\n    ".join(f"{c.name.upper()} {c.snowflake_type}" for c in spec.columns)
    return (
        f"CREATE TABLE IF NOT EXISTS STAGING.STG_{spec.name.upper()} (\n    LOAD_ID VARCHAR(40) NOT NULL,\n"
        f"    {cols},\n    ROW_HASH VARCHAR(64) NOT NULL\n);"
    )


def merge_statement(spec: Entity) -> str:
    pk = spec.pk.upper()
    cols = [c.upper() for c in spec.column_names]
    updates = ",\n        ".join(
        [f"t.{c} = s.{c}" for c in cols if c != pk]
        + ["t.ROW_HASH = s.ROW_HASH", "t.UPDATED_LOAD_ID = s.LOAD_ID", "t.ETL_UPDATED_AT = CURRENT_TIMESTAMP()"]
    )
    insert_cols = ", ".join([*cols, "ROW_HASH", "CREATED_LOAD_ID", "UPDATED_LOAD_ID", "ETL_CREATED_AT", "ETL_UPDATED_AT"])
    insert_vals = ", ".join([*(f"s.{c}" for c in cols), "s.ROW_HASH", "s.LOAD_ID", "s.LOAD_ID",
                             "CURRENT_TIMESTAMP()", "CURRENT_TIMESTAMP()"])
    return (
        f"MERGE INTO CURATED.{spec.name.upper()} t\n"
        f"USING (SELECT * FROM STAGING.STG_{spec.name.upper()} WHERE LOAD_ID = %(load_id)s) s\n"
        f"ON t.{pk} = s.{pk}\n"
        f"WHEN MATCHED AND t.ROW_HASH <> s.ROW_HASH THEN UPDATE SET\n        {updates}\n"
        f"WHEN NOT MATCHED THEN INSERT ({insert_cols})\n    VALUES ({insert_vals});"
    )


def render_sql_file(kind: str) -> str:
    """Used by scripts/generate_snowflake_sql.py to produce the committed .sql files."""
    if kind == "tables":
        parts = ["-- GENERATED by scripts/generate_snowflake_sql.py from src/finflow/schemas.py. Do not edit.",
                 "-- Run after 01_setup.sql. UNTESTED against a live Snowflake account.",
                 "USE DATABASE FINFLOW_DB;", ""]
        for spec in ENTITIES:
            parts += [staging_ddl(spec), "", curated_ddl(spec), ""]
        return "\n".join(parts)
    parts = ["-- GENERATED by scripts/generate_snowflake_sql.py from src/finflow/schemas.py. Do not edit.",
             "-- Idempotent MERGE per entity. %(load_id)s is the connector bind variable; when pasting into",
             "-- a worksheet replace it with a literal (e.g. 'LOAD_ID_VALUE') or use SET load_id = '...'.",
             "USE DATABASE FINFLOW_DB;", ""]
    for spec in ENTITIES:
        parts += [merge_statement(spec), ""]
    return "\n".join(parts)


def _connect():
    try:
        import snowflake.connector
    except ImportError as exc:
        raise ConfigError("Snowflake enabled but connector missing: pip install -r requirements-cloud.txt") from exc
    import os

    kwargs = {
        "account": os.environ.get("SNOWFLAKE_ACCOUNT"),
        "user": os.environ.get("SNOWFLAKE_USER"),
        "role": os.environ.get("SNOWFLAKE_ROLE"),
        "warehouse": os.environ.get("SNOWFLAKE_WAREHOUSE"),
        "database": os.environ.get("SNOWFLAKE_DATABASE", "FINFLOW_DB"),
        "autocommit": False,
    }
    key_path = os.environ.get("SNOWFLAKE_PRIVATE_KEY_PATH")
    if key_path:
        from cryptography.hazmat.primitives import serialization

        with open(key_path, "rb") as fh:
            key = serialization.load_pem_private_key(fh.read(), password=None)
        kwargs["private_key"] = key.private_bytes(
            serialization.Encoding.DER, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    else:
        kwargs["password"] = get_secret("SNOWFLAKE_PASSWORD", required=True)
    missing = [k for k in ("account", "user") if not kwargs[k]]
    if missing:
        raise ConfigError(f"Missing Snowflake settings: {missing}")
    return snowflake.connector.connect(**kwargs)


def sync_load(engine, load_id: str) -> dict[str, int]:
    """Push rows inserted/updated by `load_id` from the curated MySQL tables into Snowflake."""
    from snowflake.connector.pandas_tools import write_pandas

    frames: dict[str, pd.DataFrame] = {}
    with engine.connect() as conn:
        for spec in ENTITIES:
            cols = ", ".join([*spec.column_names, "row_hash"])
            res = conn.execute(text(f"SELECT {cols} FROM {spec.table} WHERE updated_load_id = :l"), {"l": load_id})
            df = pd.DataFrame(res.fetchall(), columns=list(res.keys()))
            df.insert(0, "load_id", load_id)
            df.columns = [c.upper() for c in df.columns]
            frames[spec.name] = df

    @retry(attempts=3, base_delay=5.0, logger=log)
    def _run() -> dict[str, int]:
        sf = _connect()
        counts: dict[str, int] = {}
        try:
            cur = sf.cursor()
            for spec in ENTITIES:  # parents first
                df = frames[spec.name]
                counts[spec.name] = len(df)
                cur.execute(f"DELETE FROM STAGING.STG_{spec.name.upper()} WHERE LOAD_ID = %(l)s", {"l": load_id})
                if len(df):
                    write_pandas(sf, df, f"STG_{spec.name.upper()}", schema="STAGING", quote_identifiers=False)
                cur.execute(merge_statement(spec), {"load_id": load_id})
            sf.commit()
            return counts
        except Exception:
            sf.rollback()
            raise
        finally:
            sf.close()

    try:
        return _run()
    except ConfigError:
        raise
    except Exception as exc:
        raise CloudIntegrationError(f"Snowflake load failed: {exc}") from exc
