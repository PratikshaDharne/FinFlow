-- =============================================================================
-- FinFlow - Snowflake setup (run as ACCOUNTADMIN / SYSADMIN + SECURITYADMIN).
-- UNTESTED against a live account. Review names, sizes and grants before running.
-- =============================================================================
CREATE WAREHOUSE IF NOT EXISTS FINFLOW_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS FINFLOW_DB;
CREATE SCHEMA IF NOT EXISTS FINFLOW_DB.RAW;       -- landed files (external stage + COPY INTO)
CREATE SCHEMA IF NOT EXISTS FINFLOW_DB.STAGING;   -- per-load staging tables
CREATE SCHEMA IF NOT EXISTS FINFLOW_DB.CURATED;   -- conformed, merged tables

-- Least-privilege roles
CREATE ROLE IF NOT EXISTS FINFLOW_ETL_ROLE;       -- pipeline service role: DML + stage use, no DDL on CURATED
CREATE ROLE IF NOT EXISTS FINFLOW_READER_ROLE;    -- analysts: read curated only
GRANT USAGE ON WAREHOUSE FINFLOW_WH TO ROLE FINFLOW_ETL_ROLE;
GRANT USAGE ON WAREHOUSE FINFLOW_WH TO ROLE FINFLOW_READER_ROLE;
GRANT USAGE ON DATABASE FINFLOW_DB TO ROLE FINFLOW_ETL_ROLE;
GRANT USAGE ON DATABASE FINFLOW_DB TO ROLE FINFLOW_READER_ROLE;
GRANT USAGE ON ALL SCHEMAS IN DATABASE FINFLOW_DB TO ROLE FINFLOW_ETL_ROLE;
GRANT USAGE ON SCHEMA FINFLOW_DB.CURATED TO ROLE FINFLOW_READER_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA FINFLOW_DB.STAGING TO ROLE FINFLOW_ETL_ROLE;
GRANT SELECT, INSERT, UPDATE ON FUTURE TABLES IN SCHEMA FINFLOW_DB.CURATED TO ROLE FINFLOW_ETL_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FINFLOW_DB.CURATED TO ROLE FINFLOW_READER_ROLE;

