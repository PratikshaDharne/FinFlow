-- Snowflake <-> Azure Data Lake Storage Gen2 (UNTESTED). Replace <placeholders>.
-- Uses a STORAGE INTEGRATION (Azure service principal consent) - no keys or SAS tokens in SQL.
USE ROLE ACCOUNTADMIN;
CREATE STORAGE INTEGRATION IF NOT EXISTS FINFLOW_AZURE_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'AZURE'
  ENABLED = TRUE
  AZURE_TENANT_ID = '<tenant-guid>'
  STORAGE_ALLOWED_LOCATIONS = ('azure://<storageaccount>.blob.core.windows.net/raw/');
-- Then: DESC STORAGE INTEGRATION FINFLOW_AZURE_INT;  -> open AZURE_CONSENT_URL, grant consent, and give the
-- generated service principal the "Storage Blob Data Reader" role on the container (least privilege).
GRANT USAGE ON INTEGRATION FINFLOW_AZURE_INT TO ROLE FINFLOW_ETL_ROLE;

USE ROLE SYSADMIN;
USE DATABASE FINFLOW_DB;
CREATE FILE FORMAT IF NOT EXISTS RAW.FF_CSV
  TYPE = CSV FIELD_OPTIONALLY_ENCLOSED_BY = '"' SKIP_HEADER = 1 NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;
CREATE STAGE IF NOT EXISTS RAW.STG_AZURE_RAW
  URL = 'azure://<storageaccount>.blob.core.windows.net/raw/'
  STORAGE_INTEGRATION = FINFLOW_AZURE_INT
  FILE_FORMAT = RAW.FF_CSV;
GRANT USAGE ON STAGE RAW.STG_AZURE_RAW TO ROLE FINFLOW_ETL_ROLE;
GRANT USAGE ON FILE FORMAT RAW.FF_CSV TO ROLE FINFLOW_ETL_ROLE;
