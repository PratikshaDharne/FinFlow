"""Generate docs/data_dictionary.md and docs/source_to_target_mapping.md from schemas.py.

    python scripts/generate_docs.py
"""
from pathlib import Path

from finflow.schemas import AUDIT_COLUMNS, ENTITIES, STAGING_EXTRA_COLUMNS

DOCS = Path(__file__).resolve().parents[1] / "docs"
MYSQL_TYPE = {"date": "DATE", "datetime": "DATETIME", "decimal": "DECIMAL(18,2)"}


def rules(c) -> str:
    out = []
    if c.required:
        out.append("required")
    if c.kind == "enum":
        out.append("one of " + "/".join(c.enum))
    if c.pattern:
        out.append(f"regex `{c.pattern}`")
    if c.kind == "date":
        out.append("YYYY-MM-DD, not in future")
    if c.kind == "datetime":
        out.append("YYYY-MM-DD HH:MM:SS, not in future")
    if c.kind == "decimal":
        out.append("max 2 decimals" + (", > 0" if c.min_value is not None and not c.min_inclusive else
                                       ", >= 0" if c.min_value is not None else ""))
    if c.max_len and c.kind in {"str", "enum"}:
        out.append(f"max {c.max_len} chars")
    if c.case:
        out.append(f"standardised to {c.case}case")
    if c.strip_chars:
        out.append("spaces/dashes/brackets removed")
    return "; ".join(out) or "-"


def sql_type(c) -> str:
    if c.kind in MYSQL_TYPE:
        return MYSQL_TYPE[c.kind]
    return f"VARCHAR({c.max_len or max(len(v) for v in c.enum)})"


dd = ["# Data dictionary", "",
      "> Generated by `python scripts/generate_docs.py` from `src/finflow/schemas.py`. Do not edit by hand.", ""]
for e in ENTITIES:
    dd += [f"## `{e.table}`", "", e.description, "",
           f"Primary key: `{e.pk}`. " + ("Foreign keys: " + ", ".join(
               f"`{f.column}` -> `{f.ref_entity}.{f.ref_column}`" for f in e.foreign_keys) + "." if e.foreign_keys else ""),
           "", "| Column | Logical type (exact DDL: sql/mysql) | Validation / standardisation rules | PII |", "|---|---|---|---|"]
    for c in e.columns:
        dd.append(f"| `{c.name}` | {sql_type(c)}{'' if c.required else ' NULL'} | {rules(c)} | {'yes' if c.pii else ''} |")
    dd += ["", "Audit columns added by the pipeline (curated): " + ", ".join(f"`{a}`" for a in AUDIT_COLUMNS) + ".", ""]
dd += ["## ETL control tables", "",
       "| Table | Purpose |", "|---|---|",
       "| `etl_load_audit` | One row per run: status, timings, Azure/Snowflake status, error text |",
       "| `etl_file_registry` | SHA-256 of every loaded file; unique per (entity, sha256) -> duplicate-file prevention |",
       "| `etl_watermark` | Highest `updated_at` loaded per entity (incremental loading) |",
       "| `etl_rejected_records` | Every rejected row with rule codes (PII masked by default) |",
       "| `etl_dq_results` | Failed-row counts per data-quality rule per load |",
       "| `etl_reconciliation` | Source-to-target row-count and financial-total checks (PASS/FAIL) |",
       "| `stg_<entity>` | Staging copy of validated rows for a load, keyed by `load_id` |", "",
       "Staging extra columns: " + ", ".join(f"`{c}`" for c in STAGING_EXTRA_COLUMNS) + ".", ""]
(DOCS / "data_dictionary.md").write_text("\n".join(dd), encoding="utf-8", newline="\n")

st = ["# Source-to-target mapping", "",
      "> Generated by `python scripts/generate_docs.py` from `src/finflow/schemas.py`. Do not edit by hand.", "",
      "Layers: **source CSV** -> **raw** (immutable file copy, optionally Azure Blob) -> **staging** (`stg_*`, validated) -> "
      "**curated** (MySQL / Snowflake `CURATED`).", ""]
for e in ENTITIES:
    st += [f"## {e.name}.csv -> `{e.stg_table}` -> `{e.table}`", "",
           "| Source column | Transformation | Staging column | Curated column |", "|---|---|---|---|"]
    for c in e.columns:
        t = []
        if c.case:
            t.append(f"{c.case}case")
        if c.strip_chars:
            t.append("strip separators")
        if c.kind == "decimal":
            t.append("quantise to 2 dp")
        if c.kind in {"date", "datetime"}:
            t.append("normalise ISO format")
        st.append(f"| `{c.name}` | trim, empty->NULL{', ' + ', '.join(t) if t else ''} | `{c.name}` | `{c.name}` |")
    st += ["| _(derived)_ | SHA-256 of all business columns (change detection) | `row_hash` | `row_hash` |",
           "| _(derived)_ | raw file name | `source_file` | `source_file` |",
           "| _(derived)_ | CSV line number | `source_row_number` | - |",
           "| _(derived)_ | load identifier | `load_id` | `created_load_id`, `updated_load_id` |",
           "| _(derived)_ | load timestamp (UTC) | `staged_at` | `etl_created_at`, `etl_updated_at` |", ""]
(DOCS / "source_to_target_mapping.md").write_text("\n".join(st), encoding="utf-8", newline="\n")
print("docs generated")
